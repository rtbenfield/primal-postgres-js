import { describe } from "node:test";
import { expect, test } from "vitest";
import { BinaryTypeParser } from "./mod";
import { GEOGRAPHY, GEOMETRY } from "./postgis";

const types = new BinaryTypeParser();

test("geography decoding", () => {
  const buffer = new Uint8Array([
    // endianness
    0x01,
    // geometry type
    0x01, 0x00, 0x00, 0x20,
    // SRID
    0xe6, 0x10, 0x00, 0x00,
    // longitude
    0x3c, 0xdb, 0xa3, 0x37, 0xdc, 0xc3, 0x51, 0xc0,
    // latitude
    0x6d, 0x37, 0xc1, 0x37, 0x4d, 0x37, 0x48, 0x40,
  ]);
  expect(GEOGRAPHY.decode(buffer, types)).toEqual({
    geometryType: 536870913,
    latitude: 48.432044,
    longitude: -71.060316,
    srid: 4326,
  });
});

describe("geometry decoding", () => {
  test("geometry point", () => {
    const buffer = new Uint8Array([
      // endianness
      0x01,
      // geometry type
      0x01, 0x00, 0x00, 0x20,
      // SRID
      0xe6, 0x10, 0x00, 0x00,
      // x
      0x3c, 0xdb, 0xa3, 0x37, 0xdc, 0xc3, 0x51, 0xc0,
      // y
      0x6d, 0x37, 0xc1, 0x37, 0x4d, 0x37, 0x48, 0x40,
    ]);
    expect(GEOMETRY.decode(buffer, types)).toEqual({
      geometryType: 536870913,
      srid: 4326,
      x: -71.060316,
      y: 48.432044,
    });
  });

  test("geometry polygon", () => {
    const buffer = new Uint8Array([
      // endianness
      0x01,
      // geometry type
      0x03, 0x00, 0x00, 0x20,
      // SRID
      0xe6, 0x10, 0x00, 0x00,
      // geometry data
      0x01, 0x00, 0x00, 0x00,
      // number of points
      0x05, 0x00, 0x00, 0x00,
      // point 1 x
      0x3c, 0xdb, 0xa3, 0x37, 0xdc, 0xc3, 0x51, 0xc0,
      // point 1 y
      0x6d, 0x37, 0xc1, 0x37, 0x4d, 0x37, 0x48, 0x40,
      // point 2 x
      0x3c, 0xdb, 0xa3, 0x37, 0xdc, 0xc3, 0x51, 0xc0,
      // point 2 y
      0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x48, 0x40,
      // point 3 x
      0x00, 0x00, 0x00, 0x00, 0x00, 0xc0, 0x51, 0xc0,
      // point 3 y
      0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x48, 0x40,
      // point 4 x
      0x00, 0x00, 0x00, 0x00, 0x00, 0xc0, 0x51, 0xc0,
      // point 4 y
      0x6d, 0x37, 0xc1, 0x37, 0x4d, 0x37, 0x48, 0x40,
      // ?
      0x3c, 0xdb, 0xa3, 0x37, 0xdc, 0xc3, 0x05,
    ]);
    expect(GEOMETRY.decode(buffer, types)).toEqual({
      geometryType: 536870915,
      srid: 4326,
      points: [
        { x: -71.060316, y: 48.432044 },
        { x: -71.060316, y: 48.5 },
        { x: -71, y: 48.5 },
        { x: -71, y: 48.432044 },
      ],
    });
  });
});
